BEGIN;

CREATE TABLE IF NOT EXISTS pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_pago VARCHAR(40) NOT NULL UNIQUE,
  cita_id BIGINT NOT NULL REFERENCES citas(id),
  paciente_id BIGINT NOT NULL REFERENCES pacientes(id),
  monto NUMERIC(10,2) NOT NULL CHECK (monto > 0),
  moneda CHAR(3) NOT NULL DEFAULT 'BOB' CHECK (moneda = 'BOB'),
  metodo VARCHAR(20) NOT NULL CHECK (metodo IN ('efectivo','qr','tarjeta','transferencia')),
  estado VARCHAR(15) NOT NULL DEFAULT 'pagado' CHECK (estado IN ('pagado','anulado')),
  referencia VARCHAR(100),
  observaciones VARCHAR(500),
  registrado_por BIGINT NOT NULL REFERENCES usuarios(id),
  pagado_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  anulado_at TIMESTAMPTZ,
  anulado_por BIGINT REFERENCES usuarios(id),
  motivo_anulacion VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((estado = 'pagado' AND anulado_at IS NULL AND anulado_por IS NULL)
      OR (estado = 'anulado' AND anulado_at IS NOT NULL AND anulado_por IS NOT NULL AND motivo_anulacion IS NOT NULL)),
  CHECK (metodo = 'efectivo' OR referencia IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_pago_activo_por_cita ON pagos(cita_id) WHERE estado = 'pagado';
CREATE INDEX IF NOT EXISTS idx_pagos_fecha ON pagos(pagado_at DESC);
CREATE INDEX IF NOT EXISTS idx_pagos_paciente ON pagos(paciente_id,pagado_at DESC);
CREATE INDEX IF NOT EXISTS idx_pagos_estado_metodo ON pagos(estado,metodo,pagado_at DESC);

CREATE TABLE IF NOT EXISTS historial_pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pago_id BIGINT NOT NULL REFERENCES pagos(id),
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  accion VARCHAR(20) NOT NULL CHECK (accion IN ('registro','anulacion')),
  comentario VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_historial_pagos_pago ON historial_pagos(pago_id,created_at DESC);

COMMIT;
