CREATE OR REPLACE FUNCTION registrar_historial_cita() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_actor BIGINT := NULLIF(current_setting('app.usuario_id', true), '')::BIGINT;
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO historial_citas(cita_id,usuario_id,accion,estado_nuevo,inicio_nuevo,fin_nuevo)
    VALUES (NEW.id,COALESCE(v_actor,NEW.registrado_por),'creacion',NEW.estado,NEW.inicio,NEW.fin);
  ELSIF OLD.estado IS DISTINCT FROM NEW.estado OR OLD.inicio IS DISTINCT FROM NEW.inicio OR OLD.fin IS DISTINCT FROM NEW.fin THEN
    INSERT INTO historial_citas(cita_id,usuario_id,accion,estado_anterior,estado_nuevo,inicio_anterior,fin_anterior,inicio_nuevo,fin_nuevo,comentario)
    VALUES (NEW.id,v_actor,
      CASE WHEN OLD.inicio IS DISTINCT FROM NEW.inicio OR OLD.fin IS DISTINCT FROM NEW.fin
        THEN 'reprogramacion'::accion_historial ELSE 'cambio_estado'::accion_historial END,
      OLD.estado,NEW.estado,OLD.inicio,OLD.fin,NEW.inicio,NEW.fin,
      CASE WHEN NEW.estado='cancelada' THEN LEFT(NEW.motivo_cancelacion,500) ELSE NULL END);
  END IF;
  RETURN NEW;
END;$$;

CREATE OR REPLACE FUNCTION notificar_cambio_cita() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_mensaje TEXT;
BEGIN
  IF TG_OP='UPDATE' THEN
    IF OLD.estado IS NOT DISTINCT FROM NEW.estado AND OLD.inicio IS NOT DISTINCT FROM NEW.inicio AND OLD.fin IS NOT DISTINCT FROM NEW.fin THEN RETURN NEW; END IF;
  END IF;
  v_mensaje := 'Cita ' || NEW.codigo_cita || ': ' || replace(NEW.estado::text,'_',' ') ||
    '. Fecha: ' || to_char(NEW.inicio,'DD/MM/YYYY HH24:MI') || '.';
  IF TG_OP='UPDATE' THEN
    IF OLD.inicio IS DISTINCT FROM NEW.inicio THEN v_mensaje := 'Reprogramación. ' || v_mensaje; END IF;
  END IF;
  INSERT INTO notificaciones(usuario_id,cita_id,mensaje)
    SELECT DISTINCT u.id,NEW.id,v_mensaje FROM usuarios u
    WHERE u.activo AND (u.id=(SELECT usuario_id FROM pacientes WHERE id=NEW.paciente_id)
      OR u.id=(SELECT usuario_id FROM medicos WHERE id=NEW.medico_id));
  RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS tr_notificar_cita ON citas;
CREATE TRIGGER tr_notificar_cita AFTER INSERT OR UPDATE ON citas FOR EACH ROW EXECUTE FUNCTION notificar_cambio_cita();

