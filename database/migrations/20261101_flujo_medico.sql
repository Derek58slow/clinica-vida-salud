-- La disponibilidad no puede invalidar reservas activas ya asignadas.
CREATE OR REPLACE FUNCTION proteger_horario_atencion() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_medico BIGINT;
BEGIN
  IF TG_OP='DELETE' THEN v_medico:=OLD.medico_id; ELSE v_medico:=NEW.medico_id; END IF;
  IF TG_OP='UPDATE' THEN
    PERFORM pg_advisory_xact_lock(424200,LEAST(OLD.medico_id,NEW.medico_id)::INTEGER);
    PERFORM pg_advisory_xact_lock(424200,GREATEST(OLD.medico_id,NEW.medico_id)::INTEGER);
  ELSE PERFORM pg_advisory_xact_lock(424200,v_medico::INTEGER); END IF;
  IF TG_OP IN ('UPDATE','DELETE') THEN
    IF OLD.activo AND EXISTS(SELECT 1 FROM citas c WHERE c.medico_id=OLD.medico_id
      AND c.estado IN ('solicitada','confirmada') AND c.fin>CURRENT_TIMESTAMP
      AND EXTRACT(ISODOW FROM c.inicio)=OLD.dia_semana
      AND c.inicio::time>=OLD.hora_inicio AND c.fin::time<=OLD.hora_fin) THEN
      IF TG_OP='DELETE' THEN RAISE EXCEPTION USING ERRCODE='PVS01',MESSAGE='El horario tiene citas activas pendientes'; END IF;
      IF (OLD.medico_id,OLD.dia_semana,OLD.hora_inicio,OLD.hora_fin,OLD.intervalo_minutos,OLD.activo)
        IS DISTINCT FROM (NEW.medico_id,NEW.dia_semana,NEW.hora_inicio,NEW.hora_fin,NEW.intervalo_minutos,NEW.activo)
      THEN RAISE EXCEPTION USING ERRCODE='PVS01',MESSAGE='El horario tiene citas activas pendientes'; END IF;
    END IF;
  END IF;
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  IF NEW.activo AND EXISTS(SELECT 1 FROM horarios_atencion h WHERE h.medico_id=NEW.medico_id
    AND h.dia_semana=NEW.dia_semana AND h.activo AND h.id<>NEW.id
    AND NEW.hora_inicio<h.hora_fin AND NEW.hora_fin>h.hora_inicio)
  THEN RAISE EXCEPTION USING ERRCODE='23P01',MESSAGE='El horario se superpone con otro turno activo'; END IF;
  RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS tr_proteger_horario ON horarios_atencion;
CREATE TRIGGER tr_proteger_horario BEFORE INSERT OR UPDATE OR DELETE ON horarios_atencion
FOR EACH ROW EXECUTE FUNCTION proteger_horario_atencion();
COMMIT;
