-- CLINICA VIDA SALUD - Esquema inicial integral para PostgreSQL 18
-- Ejecutar UNA sola vez sobre una BASE DE DATOS NUEVA Y VACIA.
-- No contiene DROP TABLE ni elimina datos.
-- Usar PostgreSQL con permisos para CREATE EXTENSION (p. ej. usuario postgres local).
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TYPE cita_estado AS ENUM ('solicitada','confirmada','cancelada','completada','no_asistio');
CREATE TYPE notificacion_estado AS ENUM ('pendiente','enviada','fallida');
CREATE TYPE modalidad_cita AS ENUM ('presencial','virtual');
CREATE TYPE accion_historial AS ENUM ('creacion','cambio_estado','reprogramacion','actualizacion');

-- 1. Seguridad
CREATE TABLE roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL UNIQUE,
  descripcion TEXT
);
CREATE TABLE permisos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(90) NOT NULL UNIQUE,
  descripcion TEXT
);
CREATE TABLE roles_permisos (
  rol_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permiso_id BIGINT NOT NULL REFERENCES permisos(id) ON DELETE CASCADE,
  PRIMARY KEY (rol_id, permiso_id)
);
CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rol_id BIGINT NOT NULL REFERENCES roles(id),
  nombre_usuario VARCHAR(80) UNIQUE,
  nombre VARCHAR(120) NOT NULL,
  correo VARCHAR(255) UNIQUE,
  telefono VARCHAR(30),
  contrasena_hash VARCHAR(255) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT usuarios_login_valido CHECK (nombre_usuario IS NOT NULL OR correo IS NOT NULL)
);
CREATE UNIQUE INDEX uq_usuarios_nombre_usuario_lower ON usuarios(lower(nombre_usuario)) WHERE nombre_usuario IS NOT NULL;
CREATE UNIQUE INDEX uq_usuarios_correo_lower ON usuarios(lower(correo)) WHERE correo IS NOT NULL;

-- 2. Pacientes: una ficha puede existir sin cuenta para login
CREATE TABLE pacientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT UNIQUE REFERENCES usuarios(id) ON DELETE SET NULL,
  nombres VARCHAR(100) NOT NULL,
  apellidos VARCHAR(100) NOT NULL,
  documento_identidad VARCHAR(50) UNIQUE,
  fecha_nacimiento DATE,
  sexo VARCHAR(20) CHECK (sexo IN ('femenino','masculino','otro','no_especificado')),
  telefono VARCHAR(30),
  correo VARCHAR(255),
  direccion TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_pacientes_apellidos ON pacientes(apellidos, nombres);

-- Información sensible: acceso limitado desde PHP a usuarios autorizados.
CREATE TABLE informacion_medica_paciente (
  paciente_id BIGINT PRIMARY KEY REFERENCES pacientes(id) ON DELETE CASCADE,
  tipo_sangre VARCHAR(5) CHECK (tipo_sangre IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  alergias TEXT,
  enfermedades_cronicas TEXT,
  medicamentos TEXT,
  antecedentes TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE contactos_emergencia (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id BIGINT NOT NULL REFERENCES pacientes(id) ON DELETE CASCADE,
  nombre VARCHAR(120) NOT NULL,
  parentesco VARCHAR(70),
  telefono VARCHAR(30) NOT NULL
);

-- 3. Médicos
CREATE TABLE medicos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT UNIQUE REFERENCES usuarios(id) ON DELETE SET NULL,
  nombres VARCHAR(100) NOT NULL,
  apellidos VARCHAR(100) NOT NULL,
  numero_licencia VARCHAR(80) NOT NULL UNIQUE,
  telefono VARCHAR(30),
  correo VARCHAR(255),
  consultorio VARCHAR(100),
  sede VARCHAR(150),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE especialidades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  descripcion TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE medicos_especialidades (
  medico_id BIGINT NOT NULL REFERENCES medicos(id),
  especialidad_id BIGINT NOT NULL REFERENCES especialidades(id),
  PRIMARY KEY (medico_id, especialidad_id)
);

-- 4. Agenda: dia_semana ISO: lunes=1, domingo=7.
CREATE TABLE horarios_atencion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medico_id BIGINT NOT NULL REFERENCES medicos(id),
  dia_semana SMALLINT NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  intervalo_minutos SMALLINT NOT NULL CHECK (intervalo_minutos > 0),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (hora_fin > hora_inicio)
);
CREATE INDEX idx_horarios_medico_dia ON horarios_atencion(medico_id,dia_semana);

CREATE TABLE bloqueos_horario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medico_id BIGINT NOT NULL REFERENCES medicos(id),
  inicio TIMESTAMP NOT NULL,
  fin TIMESTAMP NOT NULL,
  motivo VARCHAR(250),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fin > inicio),
  CONSTRAINT sin_bloqueos_superpuestos EXCLUDE USING gist
    (medico_id WITH =, tsrange(inicio,fin,'[)') WITH &&)
);

-- 5. Citas: el rango [inicio, fin) permite citas adyacentes
CREATE TABLE citas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_cita VARCHAR(40) NOT NULL UNIQUE,
  paciente_id BIGINT NOT NULL REFERENCES pacientes(id),
  medico_id BIGINT NOT NULL REFERENCES medicos(id),
  especialidad_id BIGINT NOT NULL,
  inicio TIMESTAMP NOT NULL,
  fin TIMESTAMP NOT NULL,
  modalidad modalidad_cita NOT NULL DEFAULT 'presencial',
  estado cita_estado NOT NULL DEFAULT 'solicitada',
  motivo VARCHAR(500),
  motivo_cancelacion TEXT,
  registrado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (fin > inicio),
  FOREIGN KEY (medico_id, especialidad_id)
    REFERENCES medicos_especialidades(medico_id, especialidad_id),
  CONSTRAINT sin_citas_superpuestas EXCLUDE USING gist
    (medico_id WITH =, tsrange(inicio,fin,'[)') WITH &&)
    WHERE (estado IN ('solicitada','confirmada'))
);
CREATE INDEX idx_citas_paciente_inicio ON citas(paciente_id,inicio DESC);
CREATE INDEX idx_citas_medico_inicio ON citas(medico_id,inicio);
CREATE INDEX idx_citas_estado_inicio ON citas(estado,inicio);

-- 6. Seguimiento: insertado automáticamente en cada alta y cambio relevante
CREATE TABLE historial_citas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cita_id BIGINT NOT NULL REFERENCES citas(id),
  usuario_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
  accion accion_historial NOT NULL,
  estado_anterior cita_estado,
  estado_nuevo cita_estado NOT NULL,
  inicio_anterior TIMESTAMP,
  fin_anterior TIMESTAMP,
  inicio_nuevo TIMESTAMP NOT NULL,
  fin_nuevo TIMESTAMP NOT NULL,
  comentario VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_historial_citas_cita ON historial_citas(cita_id,created_at DESC);

CREATE TABLE notificaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  cita_id BIGINT REFERENCES citas(id),
  mensaje VARCHAR(1000) NOT NULL,
  estado notificacion_estado NOT NULL DEFAULT 'pendiente',
  enviada_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Actualizar marca de modificación
CREATE FUNCTION actualizar_timestamp() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;$$;
CREATE TRIGGER tr_usuarios_timestamp BEFORE UPDATE ON usuarios FOR EACH ROW EXECUTE FUNCTION actualizar_timestamp();
CREATE TRIGGER tr_pacientes_timestamp BEFORE UPDATE ON pacientes FOR EACH ROW EXECUTE FUNCTION actualizar_timestamp();
CREATE TRIGGER tr_medicos_timestamp BEFORE UPDATE ON medicos FOR EACH ROW EXECUTE FUNCTION actualizar_timestamp();
CREATE TRIGGER tr_citas_timestamp BEFORE UPDATE ON citas FOR EACH ROW EXECUTE FUNCTION actualizar_timestamp();

-- Al reservar, verificar que el medico este habilitado, sin bloqueos,
-- dentro de horarios, en intervalos correctos. No permitir fechas partidas en dos dias.
-- Bloqueos y citas adquieren el mismo candado por medico para reducir carreras.
CREATE FUNCTION validar_cita() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_dia INTEGER;
BEGIN
  PERFORM pg_advisory_xact_lock(424200, NEW.medico_id::INTEGER);
  IF NEW.estado IN ('solicitada','confirmada') THEN
    IF NEW.inicio::DATE <> NEW.fin::DATE THEN
      RAISE EXCEPTION 'La cita debe empezar y terminar el mismo dia';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM medicos WHERE id=NEW.medico_id AND activo) THEN
      RAISE EXCEPTION 'El medico no esta activo';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pacientes WHERE id=NEW.paciente_id AND activo) THEN
      RAISE EXCEPTION 'El paciente no esta activo';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM especialidades WHERE id=NEW.especialidad_id AND activo) THEN
      RAISE EXCEPTION 'La especialidad no esta activa';
    END IF;
    IF EXISTS (
      SELECT 1 FROM bloqueos_horario b
      WHERE b.medico_id=NEW.medico_id
        AND tsrange(b.inicio,b.fin,'[)') && tsrange(NEW.inicio,NEW.fin,'[)')
    ) THEN
      RAISE EXCEPTION 'El medico tiene el horario bloqueado';
    END IF;
    v_dia := EXTRACT(ISODOW FROM NEW.inicio)::INTEGER;
    IF NOT EXISTS (
      SELECT 1 FROM horarios_atencion h
      WHERE h.medico_id = NEW.medico_id AND h.activo
        AND h.dia_semana=v_dia
        AND NEW.inicio::TIME >= h.hora_inicio AND NEW.fin::TIME <= h.hora_fin
        AND MOD(EXTRACT(EPOCH FROM (NEW.inicio::TIME - h.hora_inicio))::INTEGER, h.intervalo_minutos*60)=0
        AND EXTRACT(EPOCH FROM (NEW.fin-NEW.inicio))::INTEGER = h.intervalo_minutos*60
    ) THEN
      RAISE EXCEPTION 'La cita esta fuera del horario o no respeta su duracion/intervalo';
    END IF;
  END IF;
  RETURN NEW;
END;$$;
CREATE TRIGGER tr_validar_cita BEFORE INSERT OR UPDATE ON citas
FOR EACH ROW EXECUTE FUNCTION validar_cita();

-- No permitir bloquear un horario si ya hay citas activas en ese rango.
CREATE FUNCTION validar_bloqueo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM pg_advisory_xact_lock(424200, NEW.medico_id::INTEGER);
  IF EXISTS (
    SELECT 1 FROM citas c
    WHERE c.medico_id=NEW.medico_id AND c.estado IN ('solicitada','confirmada')
      AND tsrange(c.inicio,c.fin,'[)') && tsrange(NEW.inicio,NEW.fin,'[)')
  ) THEN
    RAISE EXCEPTION 'No se puede bloquear un horario con citas activas';
  END IF;
  RETURN NEW;
END;$$;
CREATE TRIGGER tr_validar_bloqueo BEFORE INSERT OR UPDATE ON bloqueos_horario
FOR EACH ROW EXECUTE FUNCTION validar_bloqueo();

CREATE FUNCTION registrar_historial_cita() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO historial_citas(cita_id,usuario_id,accion,estado_nuevo,inicio_nuevo,fin_nuevo)
    VALUES (NEW.id,NEW.registrado_por,'creacion',NEW.estado,NEW.inicio,NEW.fin);
  ELSIF OLD.estado IS DISTINCT FROM NEW.estado
       OR OLD.inicio IS DISTINCT FROM NEW.inicio
       OR OLD.fin IS DISTINCT FROM NEW.fin THEN
    INSERT INTO historial_citas(
      cita_id,usuario_id,accion,estado_anterior,estado_nuevo,
      inicio_anterior,fin_anterior,inicio_nuevo,fin_nuevo
    ) VALUES (
      NEW.id,NEW.registrado_por,
      CASE WHEN OLD.inicio IS DISTINCT FROM NEW.inicio OR OLD.fin IS DISTINCT FROM NEW.fin
           THEN 'reprogramacion'::accion_historial ELSE 'cambio_estado'::accion_historial END,
      OLD.estado,NEW.estado,OLD.inicio,OLD.fin,NEW.inicio,NEW.fin
    );
  END IF;
  RETURN NEW;
END;$$;
CREATE TRIGGER tr_historial_cita AFTER INSERT OR UPDATE ON citas
FOR EACH ROW EXECUTE FUNCTION registrar_historial_cita();

