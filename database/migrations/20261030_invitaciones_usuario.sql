-- Invitaciones seguras para activar cuentas de usuario.
-- Migración incremental: no elimina ni modifica datos existentes.
BEGIN;

CREATE TABLE IF NOT EXISTS invitaciones_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expira_at TIMESTAMPTZ NOT NULL,
    usado_at TIMESTAMPTZ,
    creado_por BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_invitaciones_usuario_vigencia
    ON invitaciones_usuario(usuario_id, expira_at)
    WHERE usado_at IS NULL;

COMMIT;
